func (svc *Service) prepareAgentCreation(ctx context.Context, caller channel.Caller, r *leapmuxv1.OpenAgentRequest, sender channel.ResponseWriter, op *creationOperation) {
	if svc.refuseIfShuttingDown(sender) {
		return
	}
	if op.record != nil {
		svc.restoreAgentCreation(op, sender)
		return
	}
	// Through the PROVIDER, because a resume handle is not one shape.
	// Claude, Codex and the ACP providers issue an opaque token, and
	// the default rule refuses one that argv could read as a flag. Pi
	// issues a session FILE PATH, which the token rule refuses by
	// design -- a Windows path holds a backslash, and a deep path runs
	// past the token byte cap -- so Pi answers for its own shape.
	// The provider resolves this handle once. Its canonical value is
	// the pending claim and the provider's resume argument. The confirmed
	// session column stays empty until the provider reports its identity.
	agentProvider := agent.ProviderOrDefault(r.GetAgentProvider())
	resumeSessionID, err := svc.Agents.Registry().Plugin(agentProvider).
		ResolveResumeHandle(r.GetAgentSessionId(), svc.HomeDir)
	if err != nil {
		sendInvalidArgument(sender, err.Error())
		return
	}

	// A client-set title is CLEANED, never refused, with the rule
	// that validate.CleanName documents. RenameAgent,
	// RenameTerminal and the plan auto-rename apply the same
	// rule, so every writer of a `title` column enforces one rule and
	// none of them fails the RPC over a title the user can neither see
	// nor correct.
	title := validate.CleanName(r.GetTitle())
	// Whether anybody CHOSE this title, recorded rather than guessed
	// later from its text. Plan-mode auto-rename overwrites only an
	// auto-generated one, and it used to decide that with a regex over
	// the rendered string -- which cannot tell a pooled name from a
	// typed `Agent Bob`, so it overwrote both.
	//
	// The client answers it, because only the client knows whether the
	// user kept the `Agent <Name>` its dialog pre-filled. A caller that
	// says nothing keeps the title it sent.
	titleAutoGenerated := r.GetTitleAutoGenerated()
	// Empty title means "you pick one" -- the client sent none, or
	// cleaning removed every character of the one it sent. Default to
	// a random "Agent <Name>" from the shared pool so CLI-spawned
	// agents match the format UI-spawned ones get. Collisions are
	// allowed (cosmetic; the user can rename either tab).
	//
	// The worker picked it, so it is auto-generated whatever the client
	// said -- a request that sends no title cannot have had one chosen.
	if title == "" {
		title = pickAgentTitle()
		titleAutoGenerated = true
	}

	agentID := r.GetCreation().GetTabId()
	agent.TraceStartupPhase(agentID, "handler_begin")

	workingDir, err := normalizeWorkingDir(r.GetWorkingDir(), svc.HomeDir, svc.HomeDir)
	if err != nil {
		sendInvalidArgument(sender, err.Error())
		return
	}

	// Validate git-mode options on the sync path so bad input (invalid
	// branch name, non-existent base branch, worktree path collision,
	// etc.) fails the RPC with InvalidArgument before we mutate any
	// state. The actual mutation happens inside runAgentStartup.
	plan, gmErr := svc.validateGitMode(ctx, workingDir, r.GetGitSetup())
	if gmErr != nil {
		sendValidationError(sender, gmErr)
		return
	}

	// Resolve the initial option selections: the client's requested values
	// (model/effort/permissionMode/provider options), filled with provider
	// defaults for any missing well-known and provider-specific ids.
	requested := mergeOptions(nil, r.GetOptions())
	launch := resolveLaunchOptions(svc.Agents.Registry(), requested, agentProvider, resumeSessionID != "")
	options := launch.Options
	// Reject a spawn whose EXPLICITLY-requested permission mode isn't valid for the provider, so a
	// typo'd --permission-mode fails fast with a clear error instead of reaching the provider and
	// dying at startup (Claude fails startup on a bad set_permission_mode). Model and effort are
	// NOT validated here: every provider discovers its model catalog (and effort tiers) from the
	// running CLI/daemon, seeding only a static fallback, so a value valid in the live catalog but
	// absent from the seed would be wrongly rejected -- the running session validates those.
	if err := svc.Agents.Registry().ValidateLaunchOptions(agentProvider, requested); err != nil {
		sendInvalidArgument(sender, err.Error())
		return
	}

	// Track whether this agent was created via session resume.
	resumed := ptrconv.BoolToInt64(resumeSessionID != "")

	agent.TraceStartupPhase(agentID, "gitmode_validated")

	// Register the startup BEFORE the row becomes visible. The startup
	// registry is the only source of STARTING: a reader that finds the row
	// of an agent that has no entry and no process reads INACTIVE. A
	// cold start in ensureAgentRunning registers before it launches for
	// the same reason, and OpenTerminal does the same for its row.
	//
	// The creation flight retains this claim across publication retries.
	// Handoff transfers it to runAgentStartup; otherwise flight teardown releases it.
	startupCtx, startupHandle, claimErr := op.acquireStartupAdmission(&svc.AgentStartup.startupCore, "")
	if claimErr != nil {
		svc.sendStartupRefused(sender, claimErr.Error())
		return
	}

	releaseWorktree, admissionErr := svc.worktreeLifecycle.admit(plan.PlannedWorkingDir)
	if admissionErr != nil {
		sendFailedPrecondition(sender, admissionErr.Error())
		return
	}
	releaseWorktree = sync.OnceFunc(releaseWorktree)
	defer releaseWorktree()

	// Persist the agent row and any prior Worker transcript under a fresh
	// background context: the DB write must survive a mid-RPC disconnect so a
	// retry from the same client doesn't observe a half-created agent
	// (the validation phase above is the only step that should
	// fail-fast on disconnect). The actual worktree mutation happens
	// later inside runAgentStartup, which uses its own startupCtx.
	intent, intentErr := svc.prepareCreationStartup(ctx, plan)
	if intentErr != nil {
		sendFailedPrecondition(sender, intentErr.Error())
		return
	}
	runtime := &agentCreationRuntime{Startup: intent, ResumeSessionID: resumeSessionID, Options: options, DefaultedIDs: launch.DefaultedIDs}
	if err := op.persist(runtime, func(ctx context.Context, q *db.Queries) error {
		return svc.createAgentRecordWithTranscriptUsing(ctx, q, db.CreateAgentParams{
			ID:                 agentID,
			WorkingDir:         plan.PlannedWorkingDir,
			Title:              title,
			TitleAutoGenerated: ptrconv.BoolToInt64(titleAutoGenerated),
			Options:            marshalOptions(options),
			AgentProvider:      agentProvider,
			Resumed:            resumed,
		}, resumeSessionID)
	}); err != nil {
		// The row does not exist, so no startup will ever run for it.
		if errors.Is(err, errNativeSessionAlreadyOpen) {
			sendFailedPrecondition(sender, err.Error())
			return
		}
		slog.Error("failed to create agent", "error", err)
		sendInternalError(sender, "failed to create agent")
		return
	}

	// The row is durable, so a reap can now find it -- but its cleanup is
	// only registered by spawnControlIPC below. Claim it so a close landing
	// in that window is remembered and the cleanup fires the moment it
	// arrives, instead of being stored for a tab nobody will close again.
	svc.agentCleanups.claim(agentID)

	dbAgent, err := svc.getAgentByID(bgCtx(), agentID)
	if err != nil {
		slog.Error("failed to fetch created agent", "error", err)
		svc.agentCleanups.abandonClaim(agentID)
		sendInternalError(sender, "failed to fetch created agent")
		return
	}

	releaseWorktree()
	svc.finishAgentCreation(op, sender, dbAgent, runtime, startupCtx, startupHandle)
}

// agentCreationRuntime contains resolved launch intent while publication is pending.
type agentCreationRuntime struct {
	Startup         creationStartupIntent
	ResumeSessionID string
	Options         OptionMap
	DefaultedIDs    map[string]bool
}

func (svc *Service) handleOpenAgent(ctx context.Context, caller channel.Caller, r *leapmuxv1.OpenAgentRequest, sender channel.ResponseWriter) {
	svc.coordinateCreation(ctx, caller, r, r.GetCreation(), leapmuxv1.TabType_TAB_TYPE_AGENT, sender, func(op *creationOperation, writer channel.ResponseWriter) {
		svc.prepareAgentCreation(op.coordinator.ctx, caller, op.request.(*leapmuxv1.OpenAgentRequest), writer, op)
	})
}

func (svc *Service) restoreAgentCreation(op *creationOperation, sender channel.ResponseWriter) {
	var runtime agentCreationRuntime
	if err := json.Unmarshal(op.record.RuntimePayload, &runtime); err != nil {
		sendInternalError(sender, err.Error())
		return
	}
	row, err := svc.getAgentByID(op.coordinator.ctx, op.key().tabID)
	if errors.Is(err, sql.ErrNoRows) || err == nil && row.ClosedAt.Valid {
		if closeErr := op.finishClosedResource(); closeErr != nil {
			sendInternalError(sender, closeErr.Error())
		} else {
			sendCreationError(sender, &creationAbortedError{message: "the created resource is closed"})
		}
		return
	}
	if err != nil {
		sendInternalError(sender, err.Error())
		return
	}
	if row.StartupError != "" {
		svc.finishCreationStartup(op, creationStartupOutcome{kind: creationStartupFailed, message: row.StartupError})
		svc.replyCommittedCreation(op, sender)
		return
	}
	op.runtime = &runtime
	// The row owns the current selection, including a pending or cleared ID.
	// The saved runtime contains the original launch intent.
	runtime.ResumeSessionID = storedSessionID(row)
	ctx, handle, claimErr := op.acquireStartupAdmission(&svc.AgentStartup.startupCore, "")
	if claimErr != nil {
		sendFailedPrecondition(sender, claimErr.Error())
		return
	}

	svc.agentCleanups.claim(row.ID)
	svc.finishAgentCreation(op, sender, row, &runtime, ctx, handle)
}

func (svc *Service) finishAgentCreation(op *creationOperation, sender channel.ResponseWriter, row db.Agent, runtime *agentCreationRuntime, startupCtx context.Context, handle *startupEntry) {
	handedOff := false
	defer func() {
		if !handedOff {
			svc.agentCleanups.retire(row.ID)

		}
	}()
	publication, err := op.publish()
	if err != nil {
		sendCreationError(sender, err)
		return
	}
	current, err := op.resolveStartupLifecycle()
	if err != nil {
		sendCreationError(sender, err)
		return
	}
	allowed, err := op.applyStartupLifecycle(current)
	if err != nil {
		sendCreationError(sender, err)
		return
	}
	if !allowed {
		op.releaseStartupAdmission()
		if latest, readErr := svc.Queries.GetAgentByID(op.coordinator.ctx, row.ID); readErr == nil {
			row = latest
		} else {
			sendInternalError(sender, readErr.Error())
			return
		}
		sendProtoResponse(sender, &leapmuxv1.OpenAgentResponse{Agent: svc.agentToProto(&row, svc.agentLivenessOf(&row), nil), Publication: publication})
		return
	}
	remoteEnvs, _, ipcErr := svc.spawnControlIPC(string(tabKindAgent), row.ID, "", svc.agentCleanups.register, func() ([]string, func(), error) {
		return svc.ControlIPC.AgentSpawning(AgentSpawnInfo{UserID: op.caller.UserID, WorkerID: svc.WorkerID, TabID: row.ID, WorkingDir: runtime.Startup.Plan.PlannedWorkingDir, AgentProvider: agentlabels.CLIAlias(row.AgentProvider)})
	})
	if ipcErr != nil {
		svc.failAgentStartup(&row, gitModeResult{}, ipcErr, nil, handle)
		svc.finishCreationStartup(op, svc.AgentStartup.creationOutcome(handle))
		sendProtoResponse(sender, &leapmuxv1.OpenAgentResponse{Agent: svc.agentToProto(&row, svc.agentLivenessOf(&row), nil), Publication: publication})
		return
	}
	opts := svc.baseAgentOptions(row.ID, runtime.Startup.Plan.PlannedWorkingDir, row.AgentProvider)
	opts.ResumeSessionID = runtime.ResumeSessionID
	opts.Options = runtime.Options
	opts.NewSessionDefaultOptionIDs = runtime.DefaultedIDs
	opts.ExtraEnv = remoteEnvs
	response := &leapmuxv1.OpenAgentResponse{Agent: svc.agentToProto(&row, svc.agentLivenessOf(&row), nil), Publication: publication}
	if err := op.handoff(handle, func() { go svc.runAgentStartup(startupCtx, row, runtime.Startup.Plan, opts, handle) }); err != nil {
		sendCreationError(sender, err)
		return
	}
	handedOff = true
	sendProtoResponse(sender, response)
}
