package deepseekharness

import (
	"context"
	"encoding/json"
	"fmt"
	"log/slog"
	"os"
	"path/filepath"
	"slices"

	"github.com/leapmux/leapmux/generated/contracts"
)

// The experimental Auto review layer of DeepSeek Harness offers the Auto
// permission preset. The dsh installation bundles the package but leaves the
// layer switched off, and the package's own patch (`cordis.patch.yml`) inserts
// this one row. The Worker inserts the same row through a launch overlay of its
// own, so every session can select Auto.
const (
	autoReviewRowID   = "auto-review"
	autoReviewPackage = "@deepseek-ai/dsh-experimental-auto-review"
)

// prepareAutoReviewOverlay writes the overlay that loads the Auto review layer
// into the private agent directory, and returns its path.
func prepareAutoReviewOverlay(directory string) (string, error) {
	rows := []any{map[string]any{"insert": []any{map[string]any{"id": autoReviewRowID, "name": autoReviewPackage}}}}
	raw, err := json.Marshal(rows)
	if err != nil {
		return "", fmt.Errorf("encode the DeepSeek Harness Auto review overlay: %w", err)
	}
	overlay := filepath.Join(directory, "auto-review.patch.yml")
	// JSON is valid YAML. The native patch loader reads the same generated bytes.
	if err := os.WriteFile(overlay, append(raw, '\n'), 0o600); err != nil {
		return "", err
	}
	return overlay, nil
}

// nativePermissionCatalog is the reply of `permissionPresets/catalog`: the
// presets that a current session can select.
type nativePermissionCatalog struct {
	Options []nativePermissionOption `json:"options"`
}

type nativePermissionOption struct {
	Value string `json:"value"`
}

// offersAutoReview reports whether the catalog lists Auto, which exists only
// while the Auto review layer is live.
func (c nativePermissionCatalog) offersAutoReview() bool {
	return slices.ContainsFunc(c.Options, func(option nativePermissionOption) bool {
		return option.Value == contracts.DeepseekHarnessPermissionPresetAuto
	})
}

// loadAutoReview reads whether the native process offers Auto. A failed read
// leaves Auto out, and the session still starts with the presets that every
// release offers.
func (a *Agent) loadAutoReview(ctx context.Context) bool {
	var catalog nativePermissionCatalog
	if err := a.rpc.call(ctx, "permissionPresets/catalog", nil, &catalog); err != nil {
		slog.Warn("DeepSeek Harness permission catalog failed, so Auto review stays unavailable", "agent_id", a.AgentID(), "error", err)
		return false
	}
	return catalog.offersAutoReview()
}

// startupPermissions returns the preset that a new process applies. A stored
// Auto that the process does not offer starts in Workspace write, the default
// preset, so the session still opens.
func startupPermissions(agentID, requested string, autoReview bool) string {
	if requested != contracts.DeepseekHarnessPermissionPresetAuto || autoReview {
		return requested
	}
	slog.Warn("DeepSeek Harness offers no Auto review, so the session starts in Workspace write", "agent_id", agentID)
	return contracts.DeepseekHarnessPermissionPresetWorkspaceWrite
}
